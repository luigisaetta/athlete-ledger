CREATE TABLE sync_state (
    provider VARCHAR2(64 CHAR) NOT NULL,
    dataset VARCHAR2(64 CHAR) NOT NULL,
    last_synced_date DATE,
    last_run_at TIMESTAMP,
    last_status VARCHAR2(32 CHAR),
    CONSTRAINT pk_sync_state PRIMARY KEY (provider, dataset)
)

/

CREATE TABLE activity (
    provider VARCHAR2(64 CHAR) NOT NULL,
    activity_id NUMBER(19) NOT NULL,
    start_time_local DATE,
    activity_name VARCHAR2(512 CHAR),
    activity_type VARCHAR2(128 CHAR),
    distance_m FLOAT,
    duration_s FLOAT,
    avg_hr_bpm FLOAT,
    calories_kcal FLOAT,
    file_status VARCHAR2(32 CHAR) DEFAULT 'not_downloaded' NOT NULL,
    source_response_id INTEGER NOT NULL,
    updated_at TIMESTAMP NOT NULL,
    CONSTRAINT pk_activity PRIMARY KEY (provider, activity_id),
    CONSTRAINT fk_activity_source_response_id FOREIGN KEY(source_response_id) REFERENCES raw_response (id)
)

/

