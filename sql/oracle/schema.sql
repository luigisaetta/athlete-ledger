CREATE TABLE raw_response (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY,
    provider VARCHAR2(64 CHAR) NOT NULL,
    endpoint VARCHAR2(256 CHAR) NOT NULL,
    params CLOB NOT NULL,
    range_start DATE,
    range_end DATE,
    fetched_at TIMESTAMP NOT NULL,
    content_sha256 VARCHAR2(64 CHAR) NOT NULL,
    sdk_version VARCHAR2(64 CHAR) NOT NULL,
    is_empty SMALLINT NOT NULL,
    payload CLOB,
    CONSTRAINT pk_raw_response PRIMARY KEY (id),
    CONSTRAINT ck_raw_response_params_json CHECK (params IS JSON),
    CONSTRAINT ck_raw_response_payload_json CHECK (payload IS JSON),
    CONSTRAINT ck_raw_response_is_empty_bool CHECK (is_empty IN (0, 1))
)

/

CREATE INDEX ix_raw_response_lookup ON raw_response (provider, endpoint, range_start)

